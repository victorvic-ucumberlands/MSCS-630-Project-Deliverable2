#!/usr/bin/env bash
# run_demos.sh - run every demo script through ./myshell and keep the evidence.
#
# Each demo runs in a fresh scratch directory (so file operations are safe and
# repeatable), with stdin from /dev/null, and its full transcript - commands
# echoed by `myshell -e`, program output and diagnostics - is written to
# evidence/<name>.log.  Afterwards a set of automatic checks (PASS/FAIL) is
# evaluated against the logs and written to evidence/SUMMARY.txt.
set -u
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SH="$ROOT/myshell"
OUT="$ROOT/evidence"
DEMOS="$ROOT/demos"

[ -x "$SH" ] || { echo "build first: make" >&2; exit 1; }
rm -rf "$OUT"; mkdir -p "$OUT"

# ---- generated stress script: limits of the parser --------------------------
python3 - "$DEMOS/06_limits.msh" <<'PY'
import sys
lines = ["# ===== DEMO 06: input limits (generated by run_demos.sh) ====="]
def pad(n):                                   # 'echo aaaa... > /dev/null' of exactly n bytes
    prefix, suffix = "echo ", " > /dev/null"
    return prefix + "a" * (n - len(prefix) - len(suffix)) + suffix
lines += ["# line of exactly 4096 bytes: accepted", pad(4096), "echo status=$?",
          "# line of 4097 bytes: rejected, shell survives", pad(4097), "echo status=$?",
          "# 256 words in one command: accepted", "echo " + " ".join(["w"] * 255) + " > /dev/null",
          "echo status=$?",
          "# 257 words: rejected", "echo " + " ".join(["w"] * 256) + " > /dev/null", "echo status=$?",
          "# a 1000-character single word is fine", "echo " + "x" * 1000 + " > /dev/null",
          "echo status=$?",
          "# 100 background jobs created in one burst, then reaped"]
lines += ["true &"] * 100
lines += ["sleep 1", "jobs", "echo burst done, shell responsive, status=$?", "exit 0"]
open(sys.argv[1], "w").write("\n".join(lines) + "\n")
PY

run_demo() {                                   # run_demo <script>
  local script="$1" name; name="$(basename "$script" .msh)"
  local work; work="$(mktemp -d)"
  {
    echo "### $name   ($(date '+%F %T'), $(uname -sr))"
    echo "### scratch dir: $work   shell: $SH"
    echo
  } > "$OUT/$name.log"
  ( cd "$work" && MYSHELL="$SH" timeout 120 "$SH" -e "$script" </dev/null >>"$OUT/$name.log" 2>&1
    rc=$?; echo >>"$OUT/$name.log"; echo "### myshell exit code: $rc" >>"$OUT/$name.log" )
  rm -rf "$work"
  echo "ran $name -> evidence/$name.log"
}
for s in "$DEMOS"/0[1-6]_*.msh; do run_demo "$s"; done

# ---- optional: interactive (pseudo-terminal) demo: Ctrl-C / Ctrl-Z / fg / bg ----
if command -v python3 >/dev/null; then
  python3 "$DEMOS/07_interactive_pty.py" "$SH" > "$OUT/07_interactive_pty.log" 2>&1
  echo "ran 07_interactive_pty -> evidence/07_interactive_pty.log"
fi

# ---- automatic checks -------------------------------------------------------
PASS=0; FAIL=0
check() {                                      # check <log> <description> <fixed-string>
  if grep -qF -- "$3" "$OUT/$1.log"; then printf 'PASS  %-18s %s\n' "$1" "$2"; PASS=$((PASS+1))
  else printf 'FAIL  %-18s %s   (missing: %s)\n' "$1" "$2" "$3"; FAIL=$((FAIL+1)); fi
}
absent() {                                     # absent <log> <description> <whole-line>
  if grep -qxF -- "$3" "$OUT/$1.log"; then printf 'FAIL  %-18s %s   (found: %s)\n' "$1" "$2" "$3"; FAIL=$((FAIL+1))
  else printf 'PASS  %-18s %s\n' "$1" "$2"; PASS=$((PASS+1)); fi
}
{
  echo "Automatic evidence checks - $(date '+%F %T')"; echo
  check 01_builtins "mkdir -p / cd / pwd work"            "/project/src"
  check 01_builtins "cat shows appended data"             "second line"
  check 01_builtins "cd - prints previous dir"            "/project"
  check 01_builtins "single quotes keep \$HOME literal"   'single $HOME not expanded'
  check 01_builtins "ls -a shows dotfile"                 ".hidden"
  check 01_builtins "2> redirect captured the error"      "cat: nosuchfile: No such file or directory"
  check 01_builtins "false gives status 1"                "false gives 1"
  check 01_builtins "external /bin/echo ran"              "hello from /bin/echo"
  check 02_process_mgmt "background jobs listed"          "Running    sleep 3 &"
  check 02_process_mgmt "SIGSTOP shows Stopped"           "Stopped (SIGSTOP)"
  check 02_process_mgmt "bg resumes job"                  "sleep 5 &"
  check 02_process_mgmt "child exit status 42 propagates" "child exited with 42"
  check 02_process_mgmt "Done notification printed"       "Done                     sleep"
  check 02_process_mgmt "kill -9 -> Killed"               "Killed"
  check 02_process_mgmt "kill -> Terminated"              "Terminated"
  check 02_process_mgmt "bg job with exit 3 reported"     "Exit 3"
  check 02_process_mgmt "SIGSEGV job reported"            "Segmentation fault"
  check 02_process_mgmt "fg of stopped job resumes"       "resumed via fg and finished, status=0"
  check 02_process_mgmt "jobs -a accounting table"        "TURN(ms)"
  check 03_errors "unknown command"                       "nosuchcommand: command not found"
  check 03_errors "not executable -> 126"                 "status=126"
  check 03_errors "cd missing dir"                        "cd: /does/not/exist: No such file or directory"
  check 03_errors "cd too many args"                      "cd: too many arguments"
  check 03_errors "cat directory"                         "cat: /tmp: Is a directory"
  check 03_errors "rmdir non-empty"                       "Directory not empty"
  check 03_errors "rm directory refused"                  "Is a directory (use rmdir)"
  check 03_errors "kill invalid pid"                      "kill: invalid pid: 'abc'"
  check 03_errors "kill 0 refused"                        "refusing to signal pid 0"
  check 03_errors "kill -1 refused"                       "refusing to signal pid -1"
  check 03_errors "kill self refused"                     "refusing to signal the shell itself"
  check 03_errors "kill bad signal"                       "invalid signal specification: BOGUS"
  check 03_errors "fg with no jobs"                       "fg: no current job"
  check 03_errors "fg unknown job"                        "fg: no such job: %99"
  check 03_errors "exit non-numeric does not exit"        "numeric argument required"
  check 03_errors "shell alive after bad exit"            "still alive after bad exit args"
  check 03_errors "unterminated quote"                    "unterminated double quote"
  check 03_errors "pipe rejected"                         "pipes ('|') are not supported yet"
  check 03_errors "syntax error near ;"                   "syntax error near unexpected token ';'"
  check 03_errors "missing redirect target"               "expected a file name after redirection operator"
  check 03_errors "stdout restored after failed redirect" "stdout is still the terminal"
  absent 03_errors "no command ran after syntax error"    "part-one-should-not-print"
  check 04_adversarial "special file names listed"        "has\"quote"
  check 04_adversarial "glued & backgrounds"              "[1] "
  check 04_adversarial "bg cat did not eat the script"    "this line was not swallowed"
  check 04_adversarial "SIGTERM-ignoring job survives TERM" "Running    /bin/sh -c"
  check 04_adversarial "stopped job killed by TERM"       "Terminated"
  check 04_adversarial "SIGKILL exit status 137"          "killed by SIGKILL -> 137"
  check 04_adversarial "exit 300 wraps to 44"             "exit 300 wraps to 44"
  check 05_nested_and_exit "nested shell exit code"       "nested shell returned 7"
  check 05_nested_and_exit "exit refused with stopped jobs" "there are stopped jobs"
  check 05_nested_and_exit "shell alive after refusal"    "shell is still running after the refused exit"
  absent 05_nested_and_exit "script stops at second exit" "THIS LINE MUST NEVER PRINT"
  check 05_nested_and_exit "remaining jobs cleaned up"    "terminating 3 remaining job(s)"
  check 06_limits "4096-byte line accepted"               "status=0"
  check 06_limits "4097-byte line rejected"               "input line too long"
  check 06_limits "257 args rejected"                     "too many arguments (limit 256)"
  check 06_limits "burst of 100 bg jobs, shell responsive" "burst done, shell responsive"
  if [ -f "$OUT/07_interactive_pty.log" ]; then
    check 07_interactive_pty "Ctrl-Z stops the foreground job" "Stopped (SIGTSTP)"
    check 07_interactive_pty "Ctrl-C kills job, shell survives" "SHELL SURVIVED CTRL-C"
    check 07_interactive_pty "fg/bg round trip"             "fg/bg round trip OK"
  fi
  # leftovers: no orphan sleeps from demo 05 may survive the shell
  if pgrep -f 'sleep 424[234]' >/dev/null; then echo "FAIL  leftovers          orphan sleep processes found"; FAIL=$((FAIL+1))
  else echo "PASS  leftovers          no orphan child processes after shell exit"; PASS=$((PASS+1)); fi
  echo; echo "Result: $PASS passed, $FAIL failed"
} | tee "$OUT/SUMMARY.txt"
[ "$FAIL" -eq 0 ]
